package io.github.ebrahimsalem1.bookingqa.core.guard;

import io.restassured.response.Response;

import java.util.List;
import java.util.Locale;
import java.util.Optional;

/**
 * Recognises when booking.com's edge (AWS WAF / CloudFront / captcha) answered instead of the
 * application. Such a response says nothing about product quality, so reporting it as a
 * product failure would be a false alarm; reporting it as a pass would be a false green.
 */
public final class BotProtectionDetector {

    private static final List<String> CHALLENGE_MARKERS = List.of(
            "awswaf", "aws-waf-token", "challenge.js", "captcha", "are you a robot",
            "request blocked", "generated by cloudfront", "access denied", "verify you are human");

    private BotProtectionDetector() {
    }

    public static Optional<String> detect(Response response) {
        return detect(response.getStatusCode(),
                response.getHeader("x-amzn-waf-action"),
                response.getHeader("x-cache"),
                safeBody(response));
    }

    /** Pure function so the heuristics are unit-testable without HTTP. */
    public static Optional<String> detect(int status, String wafActionHeader, String cacheHeader, String body) {
        if (wafActionHeader != null && !wafActionHeader.isBlank()) {
            return Optional.of("AWS WAF action '" + wafActionHeader + "' (HTTP " + status + ")");
        }
        if (status == 429) {
            return Optional.of("Rate limited by edge (HTTP 429)");
        }
        String lower = body == null ? "" : body.toLowerCase(Locale.ROOT);
        if (lower.stripLeading().startsWith("{") || lower.stripLeading().startsWith("[")) {
            // A JSON body is the application talking (e.g. a Demand API 403), not an edge challenge.
            return Optional.empty();
        }
        boolean edgeStatus = status == 202 || status == 403 || status == 405;
        if (edgeStatus) {
            for (String marker : CHALLENGE_MARKERS) {
                if (lower.contains(marker)) {
                    return Optional.of("Bot challenge page (HTTP " + status + ", marker '" + marker + "')");
                }
            }
            if (status == 202 && lower.isBlank()) {
                return Optional.of("Empty HTTP 202 from edge (silent challenge)");
            }
            if (cacheHeader != null && cacheHeader.toLowerCase(Locale.ROOT).contains("error from cloudfront")) {
                return Optional.of("CloudFront edge error (HTTP " + status + ")");
            }
        }
        return Optional.empty();
    }

    private static String safeBody(Response response) {
        try {
            String body = response.getBody().asString();
            return body.length() > 20_000 ? body.substring(0, 20_000) : body;
        } catch (RuntimeException e) {
            return "";
        }
    }
}
